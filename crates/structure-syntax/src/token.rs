#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum TokenKind {
    Ident,
    Kw(Keyword),
    /// Decimal integer, e.g. `123_456`.
    Int,
    /// Based integer, e.g. `16#FF`.
    BasedInt,
    /// Real literal, e.g. `1.0E-3`.
    Real,
    /// Single-byte character string `'...'`.
    SString,
    /// Double-byte character string `"..."`.
    DString,
    /// `T#...` / `TIME#...`
    Duration,
    /// `TOD#...` / `TIME_OF_DAY#...`
    TimeOfDay,
    /// `D#...` / `DATE#...`
    Date,
    /// `DT#...` / `DATE_AND_TIME#...`
    DateAndTime,
    /// An identifier immediately followed by `#`, e.g. `INT#` or `SPEED#`.
    TypedPrefix,
    /// `%IX1.2`, `%QW5`, `%Q*`.
    DirectVar,
    Assign,
    Arrow,
    Colon,
    Semi,
    Comma,
    Dot,
    DotDot,
    LParen,
    RParen,
    LBracket,
    RBracket,
    Plus,
    Minus,
    Star,
    Power,
    Slash,
    Amp,
    Eq,
    Ne,
    Lt,
    Le,
    Gt,
    Ge,
    /// `|`: only meaningful in graphical languages.
    Pipe,
    /// `!`: alternative vertical bar (table 1, feature 5b).
    Bang,
    Hash,
    Error,
    Eof,
}

#[derive(Clone, Debug)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
    /// A line terminator occurs between the previous token and this one.
    pub nl_before: bool,
    /// White space or a comment occurs between the previous token and this one.
    pub ws_before: bool,
    /// For error tokens: the lexical problem.
    pub error: Option<String>,
}

impl TokenKind {
    pub fn describe(self) -> &'static str {
        use TokenKind::*;
        match self {
            Ident => "identifier",
            Kw(k) => k.as_str(),
            Int | BasedInt => "integer literal",
            Real => "real literal",
            SString | DString => "character string literal",
            Duration => "duration literal",
            TimeOfDay => "time of day literal",
            Date => "date literal",
            DateAndTime => "date and time literal",
            TypedPrefix => "typed literal prefix",
            DirectVar => "directly represented variable",
            Assign => "':='",
            Arrow => "'=>'",
            Colon => "':'",
            Semi => "';'",
            Comma => "','",
            Dot => "'.'",
            DotDot => "'..'",
            LParen => "'('",
            RParen => "')'",
            LBracket => "'['",
            RBracket => "']'",
            Plus => "'+'",
            Minus => "'-'",
            Star => "'*'",
            Power => "'**'",
            Slash => "'/'",
            Amp => "'&'",
            Eq => "'='",
            Ne => "'<>'",
            Lt => "'<'",
            Le => "'<='",
            Gt => "'>'",
            Ge => "'>='",
            Pipe => "'|'",
            Bang => "'!'",
            Hash => "'#'",
            Error => "invalid token",
            Eof => "end of file",
        }
    }
}
